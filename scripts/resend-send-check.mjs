const RESEND_API_KEY = process.env.RESEND_API_KEY;
const FROM_EMAIL = process.env.RESEND_FROM_EMAIL ?? 'Formivo <onboarding@resend.dev>';

if (!RESEND_API_KEY) {
  console.log('SKIP: RESEND_API_KEY is not set in process.env');
  process.exit(0);
}

try {
  const res = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${RESEND_API_KEY}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      from: FROM_EMAIL,
      to: ['tests@formivo.invalid'],
      subject: 'Formivo invitation email verification',
      text: 'This is a verification message generated by the Formivo dev check.',
      html: '<p>This is a verification message generated by the Formivo dev check.</p>',
    }),
  });

  const body = await res.json().catch(() => ({}));

  console.log('RESEND_SEND_STATUS=', res.status);
  console.log('RESEND_SEND_BODY=', JSON.stringify(body, null, 2));

  if (res.ok) {
    console.log('RESEND_SEND=OK');
    console.log('RESEND_MESSAGE_ID=', body.data?.id ?? body.id ?? 'N/A');
    process.exit(0);
  } else {
    console.log('RESEND_SEND=NOT_OK');
    process.exit(res.status >= 500 ? 2 : 1);
  }
} catch (err) {
  console.error('RESEND_SEND_ERROR=', err instanceof Error ? err.message : String(err));
  process.exit(3);
}
